#!/usr/bin/env python3
"""Embed assets/DejaVuSans-Bold.ttf into src/ui/FontData.cpp (no runtime font files needed on the Pi)."""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent
data = (root / "assets/DejaVuSans-Bold.ttf").read_bytes()
lines = []
for i in range(0, len(data), 24):
    lines.append(",".join(str(b) for b in data[i:i+24]))
out = ("// GENERATED by tools/gen_font.py from assets/DejaVuSans-Bold.ttf (DejaVu fonts license, see assets/DejaVu-LICENSE.txt)\n"
       "#include \"FontData.h\"\n"
       "const unsigned char kFontBold[] = {\n" + ",\n".join(lines) + "\n};\n"
       f"const unsigned int kFontBoldLen = {len(data)};\n")
(root / "src/ui/FontData.cpp").write_text(out)
print("wrote", len(data), "bytes")
