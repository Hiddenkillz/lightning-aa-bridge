#!/usr/bin/env python3
# Rasterise assets/icons/*.svg (Material Design Icons, Apache-2.0) into 96x96 alpha masks embedded as C++ (src/ui/IconData.cpp). Needs rsvg-convert + Pillow.
import glob, os, subprocess, sys
from PIL import Image
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N = 96
out = ['// GENERATED by tools/gen-icons.py from assets/icons/*.svg (Material Design Icons, Apache License 2.0). Do not edit.',
       '#include "IconData.h"', 'namespace ui {']
names = []
for svg in sorted(glob.glob(os.path.join(R, 'assets/icons/*.svg'))):
    name = os.path.basename(svg)[:-4]
    png = '/tmp/icon-%s.png' % name
    subprocess.check_call(['rsvg-convert', '-w', str(N), '-h', str(N), '-o', png, svg])
    im = Image.open(png).convert('RGBA')
    variants = [(name, im)]
    if name == 'flip': variants.append(('flip_vertical', im.rotate(90, expand=True)))
    for vn, vim in variants:
        a = vim.getchannel('A').tobytes()
        out.append('static const unsigned char k_%s[%d] = {%s};' % (vn, N * N, ','.join(str(b) for b in a)))
        names.append(vn)
out.append('const IconMask* iconMask(const char* name) {')
out.append('    static const IconMask masks[] = {' + ','.join('{"%s", k_%s, %d, %d}' % (n, n, N, N) for n in names) + '};')
out.append('    for (const auto& m : masks) { const char* a = m.name; const char* b = name; while (*a && *a == *b) { ++a; ++b; } if (!*a && !*b) return &m; }')
out.append('    return nullptr;')
out.append('}')
out.append('}  // namespace ui')
open(os.path.join(R, 'src/ui/IconData.cpp'), 'w').write('\n'.join(out) + '\n')
print('icons:', names)
