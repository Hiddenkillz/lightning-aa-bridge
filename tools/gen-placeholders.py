#!/usr/bin/env python3
"""Regenerate src/ui/PlaceholderData.cpp (the placeholder artwork embedded in the binary).

Source art:  assets/placeholders/{android-auto-connecting,camera-connecting}.svg  (the permanent placeholders)
Pipeline:    render each SVG (chromium headless, 1920x1080) -> resize 1280x720 -> JPEG q92 4:4:4 -> C array.
Run from the repo root:   python3 tools/gen-placeholders.py
Needs: chromium, Pillow. The SVG animations (halo breathing, shimmer) are not used: the UI shows the still frame.
"""
import os, subprocess, sys, tempfile
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = [("AndroidAuto", "android-auto-connecting"), ("Camera", "camera-connecting")]

def render(svg, out_png):
    subprocess.run(["chromium", "--headless", "--no-sandbox", "--disable-gpu", "--hide-scrollbars", "--window-size=1920,1080",
                    f"--screenshot={out_png}", "file://" + svg], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

def main():
    lines = ["// GENERATED by tools/gen-placeholders.py - do not edit. Placeholder artwork (1280x720 JPEG) for panes without a live source.",
             '#include "Placeholder.h"', "namespace ui {"]
    with tempfile.TemporaryDirectory() as td:
        for name, base in ART:
            svg = os.path.join(ROOT, "assets", "placeholders", base + ".svg")
            png = os.path.join(td, base + ".png"); jpg = os.path.join(td, base + ".jpg")
            render(svg, png)
            im = Image.open(png).convert("RGB").resize((1280, 720), getattr(Image, "Resampling", Image).LANCZOS)
            im.save(jpg, quality=92, subsampling=0)
            data = open(jpg, "rb").read()
            # keep the reference JPEG next to the SVG as well
            open(os.path.join(ROOT, "assets", "placeholders", base + "-1280.jpg"), "wb").write(data)
            lines.append(f"const unsigned char kArt{name}[] = {{")
            for i in range(0, len(data), 24):
                lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
            lines.append("};")
            lines.append(f"const unsigned long kArt{name}Size = sizeof(kArt{name});")
    lines.append("}  // namespace ui")
    open(os.path.join(ROOT, "src", "ui", "PlaceholderData.cpp"), "w").write("\n".join(lines) + "\n")
    print("wrote src/ui/PlaceholderData.cpp")

if __name__ == "__main__":
    sys.exit(main())
